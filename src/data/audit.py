from __future__ import annotations

import argparse
import hashlib
import json
import shutil
from pathlib import Path

import cv2
import imagehash
import numpy as np
import yaml
from PIL import Image

from src.utils.config import load_yaml
from src.utils.logger import get_logger
from src.utils.paths import CONFIGS_DIR, METADATA_DIR, REPORTS_DIR

logger = get_logger("audit")

IMG_EXTS = {".jpg", ".jpeg", ".png", ".bmp", ".tif", ".tiff"}


def md5_file(path: Path) -> str:
    h = hashlib.md5()
    with open(path, "rb") as f:
        h.update(f.read())
    return h.hexdigest()


def phash_file(path: Path) -> str:
    try:
        return str(imagehash.phash(Image.open(path)))
    except Exception:
        return "NA"


def audit_static_image(path: Path) -> dict:
    try:
        img = cv2.imread(str(path), cv2.IMREAD_GRAYSCALE)
        if img is None:
            return {"readable": False, "width": None, "height": None, "error": "cv2 failed to decode"}
        h, w = img.shape
        return {"readable": True, "width": int(w), "height": int(h)}
    except Exception as exc:
        return {"readable": False, "width": None, "height": None, "error": str(exc)}


def audit_label_file(path: Path, image_w: int, image_h: int) -> dict:
    """YOLO-format txt label check."""
    if not path.exists():
        return {"empty": True, "objects": 0, "invalid_coords": 0, "bbox_out_of_bounds": 0}
    try:
        lines = [ln.strip() for ln in path.read_text().splitlines() if ln.strip()]
    except Exception:
        return {"unreadable": True}
    n_objects = 0
    invalid = 0
    oob = 0
    for ln in lines:
        parts = ln.split()
        if len(parts) < 5:
            invalid += 1
            continue
        try:
            nums = [float(p) for p in parts[1:5]]
        except ValueError:
            invalid += 1
            continue
        n_objects += 1
        cx, cy, bw, bh = nums
        if any(n < 0 for n in nums):
            invalid += 1
            continue
        if (cx + bw / 2 > 1.05 or cx - bw / 2 < -0.05 or
                cy + bh / 2 > 1.05 or cy - bh / 2 < -0.05 or bw > 1.1 or bh > 1.1 or bw <= 0 or bh <= 0):
            oob += 1
    return {"empty": n_objects == 0, "objects": n_objects, "invalid_coords": invalid, "bbox_out_of_bounds": oob}


def audit_mask(path: Path) -> dict:
    """Binary mask check (px value distribution + bounds count)."""
    try:
        img = cv2.imread(str(path), cv2.IMREAD_GRAYSCALE)
        if img is None:
            return {"readable": False}
        mask = (img > 127).astype(np.uint8)
        n_pixels = int(mask.sum())
        return {"readable": True, "mask_pixels": n_pixels, "size_ratio": round(n_pixels / max(1, img.size), 4)}
    except Exception:
        return {"readable": False}


def find_images(root: Path) -> list[Path]:
    return sorted(p for p in root.rglob("*") if p.is_file() and p.suffix.lower() in IMG_EXTS)


def find_label_txts(root: Path, image: Path) -> list[Path]:
    """Try common YOLO label conventions."""
    candidates = []
    for base in [image.parent / "labels", image.parent / "annotations", image.parent / "label_txt"]:
        cand = base / (image.stem + ".txt")
        if cand.exists():
            candidates.append(cand)
    cand = image.with_suffix(".txt")
    if cand.exists():
        candidates.append(cand)
    return candidates


def audit_dataset(name: str, root: Path, cfg: dict) -> dict:
    images = find_images(root)
    per_image = {}
    for im in images:
        rec = audit_static_image(im)
        labels = find_label_txts(root, im)
        label_info = {str(p): audit_label_file(p, rec.get("width", 0), rec.get("height", 0)) for p in labels}
        per_image[str(im)] = {"image": rec, "labels": label_info}
    return {"name": name, "n_images": len(images), "images": per_image}


def duplicate_report(root: Path, cfg: dict) -> list[dict]:
    images = find_images(root)
    sigs = {}
    rows = []
    for im in images:
        try:
            md5 = md5_file(im)
        except OSError:
            continue
        if md5 in sigs:
            rows.append({"file_a": str(sigs[md5][0]), "file_b": str(im), "type": "exact_md5"})
        else:
            sigs[md5] = [im]
    # pHash near-dup (cheap for small sets; skip if too big)
    threshold = cfg.get("phash_distance_threshold", 6)
    phash_sigs = []
    if len(images) <= 3000:
        for im in images:
            ph = phash_file(im)
            if ph != "NA":
                phash_sigs.append((str(im), ph))
        for i in range(len(phash_sigs)):
            for j in range(i + 1, len(phash_sigs)):
                d = imagehash.hex_to_hash(phash_sigs[i][1]) - imagehash.hex_to_hash(phash_sigs[j][1])
                if d <= threshold:
                    rows.append({"file_a": phash_sigs[i][0], "file_b": phash_sigs[j][0], "type": f"near_phash_d{d}"})
    return rows


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--raw", default=str(Path(__file__).parents[2] / "datasets" / "raw"))
    parser.add_argument("--out", default=str(REPORTS_DIR / "data_audit_report"))
    args = parser.parse_args()

    raw_root = Path(args.raw)
    cfg = load_yaml(CONFIGS_DIR / "audit.yaml").get("audit", {})
    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)

    report = {"raw_root": str(raw_root), "datasets": {}}
    entries = [p for p in sorted(raw_root.iterdir()) if p.is_dir()] if raw_root.exists() else []

    for ds in entries:
        logger.info(f"Auditing dataset: {ds.name}")
        rec = audit_dataset(ds.name, ds, cfg)
        rec["duplicates"] = duplicate_report(ds, cfg)
        report["datasets"][ds.name] = rec

    js = out_dir / "data_audit_report.json"
    js.write_text(json.dumps(report, indent=2, ensure_ascii=False))

    md_lines = ["# Data Audit Report", "", f"Raw root: `{raw_root}`", ""]
    for name, rec in report["datasets"].items():
        md_lines.append(f"## {name}")
        md_lines.append(f"- images: {rec['n_images']}")
        md_lines.append(f"- duplicates: {len(rec['duplicates'])}")
    (out_dir / "data_audit_report.md").write_text("\n".join(md_lines))

    logger.info(f"Audit report written to {js}")


if __name__ == "__main__":
    main()
